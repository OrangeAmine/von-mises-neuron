"""Export completed-study teaching views from pinned, tracked evidence only."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SPEC = Path("docs/learning/research_portfolio.json")
OUTPUT = Path("learning/vm_playground/research-evidence.js")


def resolve_pointer(document: Any, pointer: str) -> Any:
    """Resolve a JSON Pointer, including array indices and escaped keys."""
    if not pointer.startswith("/"):
        raise ValueError(f"Expected an absolute JSON Pointer: {pointer}")
    for segment in pointer[1:].split("/"):
        key = segment.replace("~1", "/").replace("~0", "~")
        document = document[int(key)] if isinstance(document, list) else document[key]
    return document


def _local_file(root: Path, relative: str) -> Path:
    """Require a repository-local existing source or teaching link."""
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError(f"Missing or nonlocal evidence path: {relative}")
    return path


def _number(value: Any) -> float:
    """Reject missing, Boolean and nonfinite metric values."""
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError(f"Invalid numeric evidence: {value!r}")
    return value


def build_portfolio(root: Path = ROOT) -> dict[str, Any]:
    """Build views without recomputing study estimates or scientific decisions.

    Args:
        root: Repository containing the authored specification and pinned records.

    Returns:
        Narrative views with exact source values and their traceable pointers.

    Raises:
        ValueError: If a source changed or an exported value is invalid.
    """
    data = copy.deepcopy(json.loads((root / SPEC).read_text(encoding="utf-8")))
    records = {}
    for key, source in data["sources"].items():
        path = _local_file(root, source["path"])
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != source["sha256"]:
            raise ValueError(f"Pinned evidence changed: {source['path']}")
        source["href"] = "../../" + source["path"]
        if path.suffix == ".json":
            records[key] = json.loads(raw)
    if [s["id"] for s in data["studies"]] != [f"N{i:02d}" for i in range(1, 7)]:
        raise ValueError("Expected all six studies in their declared order")
    for study in data["studies"]:
        if study["gate"] is not None:
            gate = study["gate"]
            value = resolve_pointer(records[gate["source"]], gate["pointer"])
            if value is not False:
                raise ValueError(f"Frozen scientific decision changed: {study['id']}")
            gate["passed"] = value
        for link in study["links"]:
            _local_file(root, link["path"])
        for view in study["views"]:
            for metric in view["metrics"]:
                record = records[metric["source"]]
                metric["value"] = _number(resolve_pointer(record, metric["pointer"]))
                if metric["interval_pointer"]:
                    interval = resolve_pointer(record, metric["interval_pointer"])
                    if not isinstance(interval, list) or len(interval) != 2:
                        raise ValueError("Expected a two-endpoint saved interval")
                    metric["interval"] = [_number(v) for v in interval]
                    if metric["interval"][0] > metric["interval"][1]:
                        raise ValueError("Reversed interval endpoints")
    return data


def render_javascript(data: dict[str, Any]) -> str:
    """Render a local-script export with recursively frozen evidence."""
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    return (
        "// Generated by scripts/learning/build_vm_research_portfolio.py.\n"
        "(() => {\n  'use strict';\n  const deepFreeze = value => {\n"
        "    if (value && typeof value === 'object') {\n"
        "      Object.values(value).forEach(deepFreeze); Object.freeze(value);\n"
        "    } return value;\n  };\n"
        "  Object.defineProperty(globalThis, 'VMResearchEvidence', {value: deepFreeze("
        + payload
        + "), writable: false, configurable: false});\n})();\n"
    )


def main() -> None:
    """Write the export or check it without modifying any files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    encoded = render_javascript(build_portfolio()).encode("utf-8")
    output = ROOT / OUTPUT
    if args.check:
        if not output.exists() or output.read_bytes() != encoded:
            raise SystemExit("Research export is stale; regenerate from the reviewed specification.")
        print("Verified six studies, eleven pinned sources and the current teaching export.")
    else:
        output.write_bytes(encoded)
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
